namespace MinecraftPT.Streamline;

/// <summary>
/// Режимы работы технологии NVIDIA DLSS (Super Resolution и Ray Reconstruction).
/// Соответствует перечислению <c>sl::DLSSMode</c> из заголовочного файла <c>sl_dlss.h</c> NVIDIA Streamline SDK.
/// </summary>
public enum DLSSMode : uint
{
    /// <summary>
    /// DLSS выключен. Рендеринг выполняется без масштабирования или реконструкции лучей.
    /// </summary>
    eOff = 0,

    /// <summary>
    /// Режим максимальной производительности (масштабирование ~2.0x по каждой оси, 0.5x по разрешению).
    /// </summary>
    eMaxPerformance,

    /// <summary>
    /// Сбалансированный режим (масштабирование ~1.7x по каждой оси, ~0.58x по разрешению).
    /// </summary>
    eBalanced,

    /// <summary>
    /// Режим максимального качества масштабирования (масштабирование ~1.5x по каждой оси, ~0.67x по разрешению).
    /// </summary>
    eMaxQuality,

    /// <summary>
    /// Режим ультра-производительности для экстремально высоких разрешений (4K/8K, масштабирование ~3.0x по каждой оси).
    /// </summary>
    eUltraPerformance,

    /// <summary>
    /// Режим ультра-качества (масштабирование ~1.3x по каждой оси).
    /// </summary>
    eUltraQuality,

    /// <summary>
    /// Deep Learning Anti-Aliasing (DLAA). Нативное разрешение рендеринга 1:1 без пространственного масштабирования.
    /// Нейросетевой пайплайн сглаживания и реконструкции лучей работает на полном разрешении экрана для бескомпромиссного качества.
    /// </summary>
    eDLAA,

    /// <summary>
    /// Служебное значение количества элементов перечисления.
    /// </summary>
    eCount
}
